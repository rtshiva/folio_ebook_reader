// Generates src/vendor/fonts/fonts-inline.js — the vendored reading fonts as
// data URIs, consumed by index.html's FS() @font-face builder.
//
// Why: chapter iframes render as srcdoc/blob documents whose base has no real
// directory (file:///OEBPS/…, blob:…, folio-cache://…), so file-based font
// sources fail there and text rode the CDN fallback — with font-display:swap
// the page visibly re-rendered in a different font whenever the CDN answered
// (worse: flaky per visit through proxies). data: URIs load instantly in every
// context — file://, http(s), and the packaged exe (CSP font-src already
// admits data: everywhere).
//
// Re-run whenever a font file under src/vendor/fonts changes:
//   node tests/generate-font-inline.mjs        (or: npm run fonts:inline)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = join(root, 'src', 'vendor', 'fonts');
const outFile = join(fontDir, 'fonts-inline.js');

const entries = {};
for (const f of readdirSync(fontDir).sort()) {
  if (!f.endsWith('.woff2')) continue;
  const key = f.replace(/\.woff2$/, '');
  entries[key] = 'data:font/woff2;base64,' + readFileSync(join(fontDir, f)).toString('base64');
}

const banner = '/* GENERATED by tests/generate-font-inline.mjs — do not hand-edit.\n'
  + '   Regenerate: npm run fonts:inline  (source of truth: vendor/fonts/*.woff2)\n'
  + '   Consumed by index.html FS(): data: font sources for chapter iframes\n'
  + '   whose base (srcdoc/blob/folio-cache) cannot resolve file-based URLs. */\n';
const body = 'window.FOLIO_FONT_DATA=' + JSON.stringify(entries) + ';\n';
writeFileSync(outFile, banner + body);
const kb = Math.round((banner.length + body.length) / 1024);
console.log(`fonts-inline.js written: ${Object.keys(entries).length} faces, ${kb} KB`);
