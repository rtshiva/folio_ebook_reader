// Build marker for the debug diagnostics ring (Dbg).
//   node scripts/build-flag.mjs release   -> stamps __buildflag.js with the
//        release marker + a unique build id, runs `tauri build`, then restores
//        the debug default. Release builds FORCE the debug ring off
//        (settings.debugLog is ignored and the settings toggle is disabled),
//        so a shipped installer can never ship with logging enabled.
//   node scripts/build-flag.mjs debug     -> builds with the debug marker
//        (the diagnostics toggle available; fresh build id per build).
// The build id in every dump identifies exactly which binary produced it —
// the stale-binary acceptance trap cost a false report once (two same-size
// exes, different content).
import { readFileSync, writeFileSync } from 'fs';
import { execSync } from 'child_process';

const mode = process.argv[2] || 'debug';
if (mode !== 'release' && mode !== 'debug') {
  console.error('usage: node scripts/build-flag.mjs release|debug');
  process.exit(1);
}
const flagPath = new URL('../src/__buildflag.js', import.meta.url);
const root = new URL('..', import.meta.url);
const original = readFileSync(flagPath, 'utf8');
const stamp = (mode === 'release' ? 'rel-' : 'dbg-') +
  new Date().toISOString().replace(/[-:]/g, '').replace(/\..*$/, '').replace('T', '-');
const marker = `/* GENERATED by scripts/build-flag.mjs (${mode}) — do not edit by hand. */
window.__FOLIO_RELEASE_BUILD__ = ${mode === 'release'};
window.__FOLIO_BUILD_ID__ = '${stamp}';
`;
writeFileSync(flagPath, marker);
try {
  execSync('npx tauri build', { stdio: 'inherit', cwd: root });
} finally {
  // always restore the in-tree debug default, even on a failed build
  writeFileSync(flagPath, original);
}
